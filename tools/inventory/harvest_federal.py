def _source_block(pinned, source) -> dict:
    record = source["record"]
    return {"id": source["id"], "register": source["register"],
            "rights_record": "%s#%s" % (pinned["rights"],
                                        source["rights_record"]),
            "rightsholder": clean(record["rightsholder"]),
            "work": clean(record["work"]),
            "edition": clean(record["edition"]),
            "decisions": list(pinned["decisions"]),
            "licence": source["licence"]["spdx"]}


def _counts(entries, kinds) -> dict:
    out = {"entries": len(entries)}
    for kind in kinds:
        out[kind] = sum(1 for e in entries if e["kind"] == kind)
    out["text_withheld"] = sum(1 for e in entries
                               if e["rights_status"] != RIGHTS_STATUS)
    return out


def documents_of(entries, snapshot_docs) -> list:
    used = {e["document"] for e in entries}
    return [{"evidence": d["evidence"], "sha256": d["sha256"],
             "domain": d["domain"], "edition": d.get("edition"),
             "draft": d["draft"]["value"],
             "duplicate_of": d["duplicate_of"]}
            for d in snapshot_docs if d["evidence"] in used]


STATUS_TEXT = ("source evidence (scope approval D6); not vocabulary, not an "
               "admission to the ontology (Amendment 4)")


def build(cache: Path, base: Path | None = None,
          refetch: bool = False) -> tuple[dict[str, bytes], dict]:
    """Every output, as bytes, keyed by path, and the build's evidence
    (the MITRE text set, findings). Writes nothing."""
    base = base or root()
    pinned = pins(base)
    names = outputs(pinned)
    read = Bytes(cache, refetch)
    for source in (pinned["brm"], pinned["fibf"]):
        for ref in source.get("context") or []:
            read(source["evidence"][ref])
    brm = harvest_brm(pinned, read)
    fibf = harvest_fibf(pinned, read)

    brm_doc = {"format": FORMAT, "generator": GENERATOR, "status": STATUS_TEXT,
               "source": _source_block(pinned, pinned["brm"]),
               "documents": brm["documents"],
               "counts": _counts(brm["entries"], (KIND_SECTOR,
                                                  KIND_BRM_FUNCTION,
                                                  KIND_BRM_SERVICE)),
               "entries": brm["entries"]}
    fa_doc = {"format": FORMAT, "generator": GENERATOR, "status": STATUS_TEXT,
              "source": _source_block(pinned, pinned["fibf"]),
              "snapshot": names["snapshot"],
              "documents": documents_of(fibf["fa"], fibf["documents"]),
              "counts": _counts(fibf["fa"], (KIND_FUNCTION, KIND_ACTIVITY)),
              "entries": fibf["fa"]}
    cap_doc = {"format": FORMAT, "generator": GENERATOR, "status": STATUS_TEXT,
               "source": _source_block(pinned, pinned["fibf"]),
               "snapshot": names["snapshot"],
               "homonym_note": HOMONYM_NOTE,
               "documents": documents_of(fibf["caps"], fibf["documents"]),
               "counts": _counts(fibf["caps"], (KIND_CAPABILITY,)),
               "entries": fibf["caps"]}
    statuses = [d["status"] for d in fibf["documents"]]
    snap_doc = {"format": FORMAT, "generator": GENERATOR, "status": STATUS_TEXT,
                "source": _source_block(pinned, pinned["fibf"]),
                "rules": {
                    "harvested": "no MITRE notice in rights.yaml or in the "
                                 "bytes, and no other copyright, licence or "
                                 "proprietary notice in the bytes",
                    STATUS_MITRE: "FIBF-1 c: a MITRE notice, in rights.yaml "
                                  "and in the bytes; content not harvested",
                    STATUS_AMBIGUOUS: "rights.yaml and the bytes disagree, or "
                                      "another notice is present; treated as "
                                      "restricted",
                    WITHHELD_MITRE_TEXT: "field text equal to a cell of a "
                                         "withheld MITRE-marked workbook",
                    WITHHELD_THIRD_PARTY: "field text naming the third-party "
                                          "framework, or equal to a cell of "
                                          "a FIBF-2 a mapping column or "
                                          "sheet in the same document",
                    "excluded_fibf_2a": "every column naming the third-party "
                                        "framework; `mapping` columns (header "
                                        "names it, or half the cells do) are "
                                        "never read into entries"},
                "counts": {"documents": len(statuses),
                           **{s: statuses.count(s) for s in STATUSES},
                           "draft": sum(1 for d in fibf["documents"]
                                        if d["draft"]["value"]),
                           "with_duplicate": sum(1 for d in fibf["documents"]
                                                 if d["duplicate_of"])},
                "documents": fibf["documents"]}
    built = {
        names["brm"]: (header(BRM_HEADER) + "\n" + _dump(brm_doc)).encode(
            "utf-8"),
        names["functions"]: (header(FA_HEADER) + "\n" + _dump(fa_doc)).encode(
            "utf-8"),
        names["capabilities"]: (header(CAP_HEADER) + "\n"
                                + _dump(cap_doc)).encode("utf-8"),
        names["snapshot"]: (header(SNAPSHOT_HEADER) + "\n"
                            + _dump(snap_doc)).encode("utf-8"),
        names["notice"]: notice_text(pinned),
    }
    problems = check_documents(pinned, built, base)
    problems += mitre_findings(built, names, fibf["mitre_texts"])
    if problems:
        raise Refused("the harvest built outputs its own check refuses:\n  "
                      + "\n  ".join(problems))
    return built, {"findings": fibf["findings"]}


