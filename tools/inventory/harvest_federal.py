def harvest_bpo_module(base: Path):
    spec = importlib.util.spec_from_file_location(
        "bco_harvest_bpo_for_federal", base / HARVEST_BPO)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _walk_values(data, path=""):
    if isinstance(data, dict):
        for key, value in data.items():
            yield from _walk_values(value, "%s/%s" % (path, key))
    elif isinstance(data, list):
        for n, value in enumerate(data):
            yield from _walk_values(value, "%s/%d" % (path, n))
    elif isinstance(data, str):
        yield path, data


def mitre_findings(contents: dict, names: dict, texts: set) -> list[str]:
    """No harvested name or description equals a withheld MITRE-marked
    workbook's text. Needs the bytes, so --rebuild and --confirm only."""
    out = []
    for key in ("functions", "capabilities"):
        doc = parse_yaml(contents[names[key]])
        for e in doc.get("entries") or []:
            for field in ("name", "description"):
                value = e.get(field)
                if isinstance(value, str) and len(norm(value).split()) >= 2 \
                        and norm(value) in texts:
                    out.append("%s %s equals text in a MITRE-marked workbook "
                               "(FIBF-1 c)" % (e.get("id"), field))
    return out


def _entry_findings(e, where, kinds, harvested, digests, prefixes) -> list:
    out = []
    eid = e.get("id", "<no id>")
    for key in ("id", "kind", "register", "document", "document_sha256",
                "code", "level", "parent_code", "name", "description",
                "locator", "rights_status"):
        if key not in e:
            out.append("%s %s has no %r" % (where, eid, key))
    if out:
        return out
    if e["kind"] not in kinds:
        return ["%s %s has kind %r; this file holds %s" % (where, eid,
                                                           e["kind"], kinds)]
    if e["level"] != LEVELS[e["kind"]]:
        out.append("%s level %r is not %r" % (eid, e["level"],
                                              LEVELS[e["kind"]]))
    if e["document"] not in harvested:
        out.append("%s comes from %s, which the snapshot does not mark "
                   "harvested. Was withheld content published?"
                   % (eid, e["document"]))
    if digests.get(e["document"]) != e["document_sha256"]:
        out.append("%s records digest %s for %s; rights.yaml pins %s"
                   % (eid, e["document_sha256"], e["document"],
                      digests.get(e["document"])))
    locator = e["locator"]
    if not isinstance(locator, dict) or not (
            ("sheet" in locator and isinstance(locator.get("row"), int))
            or isinstance(locator.get("page"), int)
            or isinstance(locator.get("pages"), list)
            or isinstance(locator.get("html_line"), int)):
        out.append("%s has no usable locator (sheet and row, page, or HTML "
                   "line): %r" % (eid, locator))
    prefix = prefixes[e["document"]]
    code = e["code"]
    row = locator.get("row", locator.get("html_line")) if isinstance(
        locator, dict) else None
    allowed = set()
    if code:
        allowed.add("%s-%s-%s" % (prefix, code, e["kind"]))
        allowed.add("%s-%s-r%s-%s" % (prefix, code, row, e["kind"]))
        allowed.add("%s-%s-p%s-%s" % (prefix, code, locator.get("page"),
                                      e["kind"]))
    else:
        allowed.add("%s-row%s-%s" % (prefix, row, e["kind"]))
    if eid not in allowed:
        out.append("%s is not an id its fields produce (%s)"
                   % (eid, sorted(allowed)[0]))
    withheld = False
    for field in ("name", "description"):
        value = e[field]
        if isinstance(value, dict):
            withheld = True
            if set(value) != {"withheld"} or value["withheld"] not in \
                    WITHHOLD_REASONS:
                out.append("%s %s is %r: a withheld field holds only "
                           "{withheld: <reason>}" % (eid, field, value))
        elif value is not None and not isinstance(value, str):
            out.append("%s %s is %r" % (eid, field, value))
    expected = RIGHTS_STATUS_PARTIAL if withheld else RIGHTS_STATUS
    if e["rights_status"] != expected:
        out.append("%s has rights_status %r; its fields say %r"
                   % (eid, e["rights_status"], expected))
    if e["kind"] == KIND_CAPABILITY and e.get("homonym_flag") is not True:
        out.append("%s has no homonym flag (E5): a FIBF business capability "
                   "is a requirement record, not a BCO capability" % eid)
    return out


def check_documents(pinned: dict, contents: dict[str, bytes],
                    base: Path) -> list[str]:
    import yaml

    names = outputs(pinned)
    problems = []
    for key, path in names.items():
        if path not in contents:
            problems.append("%s is missing. Run `python %s --rebuild`."
                            % (path, GENERATOR))
    if problems:
        return problems
    docs = {}
    for key in ("brm", "functions", "capabilities", "snapshot"):
        try:
            docs[key] = parse_yaml(contents[names[key]])
        except yaml.YAMLError as error:
            return ["%s does not parse as YAML: %s" % (names[key], error)]
        doc = docs[key]
        if not isinstance(doc, dict) or doc.get("format") != FORMAT or \
                doc.get("generator") != GENERATOR:
            problems.append("%s is not format %d from %s" % (names[key],
                                                             FORMAT,
                                                             GENERATOR))
    if problems:
        return problems

    brm, fibf = pinned["brm"], pinned["fibf"]
    # The snapshot: exactly rights.yaml's candidates, by digest.
    snapshot = docs["snapshot"].get("documents") or []
    listed = [(d.get("evidence"), d.get("sha256")) for d in snapshot]
    pinned_docs = [(i["id"], i["sha256"]) for i in fibf["items"]]
    if listed != pinned_docs:
        problems.append("%s lists %d documents that are not rights.yaml's %d "
                        "candidates, in order, by digest"
                        % (names["snapshot"], len(listed), len(pinned_docs)))
    harvested = set()
    for d in snapshot:
        status = d.get("status")
        if status not in STATUSES:
            problems.append("%s: %s has status %r" % (names["snapshot"],
                                                      d.get("evidence"),
                                                      status))
            continue
        marked = d.get("evidence") in fibf["mitre_marked"]
        if status == STATUS_HARVESTED:
            if marked:
                problems.append("%s is harvested, but rights.yaml records a "
                                "MITRE notice for it (FIBF-1 c)"
                                % d.get("evidence"))
            harvested.add(d.get("evidence"))
        else:
            extra = set(d) - WITHHELD_SNAPSHOT_KEYS
            if extra:
                problems.append("%s: withheld %s carries %s; a withheld "
                                "document is listed by locator, digest and "
                                "status only" % (names["snapshot"],
                                                 d.get("evidence"),
                                                 sorted(extra)))
            extra = set(d.get("rights_validation") or {}) - \
                WITHHELD_VALIDATION_KEYS
            if extra:
                problems.append("%s: withheld %s's rights_validation carries "
                                "%s" % (names["snapshot"], d.get("evidence"),
                                        sorted(extra)))
            if status == STATUS_MITRE and not marked:
                problems.append("%s is withheld-mitre but rights.yaml records "
                                "no MITRE notice; that is withheld-ambiguous"
                                % d.get("evidence"))
    counts = docs["snapshot"].get("counts") or {}
    statuses = [d.get("status") for d in snapshot]
    for s in STATUSES:
        if counts.get(s) != statuses.count(s):
            problems.append("%s counts %r %s; its documents give %d"
                            % (names["snapshot"], counts.get(s), s,
                               statuses.count(s)))

    digests = {i["id"]: i["sha256"] for i in fibf["items"]}
    digests.update({i["id"]: i["sha256"] for i in brm["items"]})
    prefixes = {i["id"]: "%s-%s" % (fibf["entry_prefix"], doc_token(i["id"]))
                for i in fibf["items"]}
    prefixes.update({i["id"]: i["entry_prefix"] for i in brm["items"]})
    brm_ids = {i["id"] for i in brm["items"]}
    recorded = [(d.get("evidence"), d.get("sha256"))
                for d in docs["brm"].get("documents") or []]
    if recorded != [(i["id"], i["sha256"]) for i in brm["items"]]:
        problems.append("%s records documents %s; the pins are both BRM "
                        "documents (BRM-2 c) by rights.yaml's digests"
                        % (names["brm"], [r[0] for r in recorded]))

    files = (("brm", (KIND_SECTOR, KIND_BRM_FUNCTION, KIND_BRM_SERVICE),
              brm_ids),
             ("functions", (KIND_FUNCTION, KIND_ACTIVITY), harvested),
             ("capabilities", (KIND_CAPABILITY,), harvested))
    for key, kinds, allowed_docs in files:
        doc = docs[key]
        entries = doc.get("entries")
        if not isinstance(entries, list) or not entries:
            problems.append("%s holds no entries" % names[key])
            continue
        ids = [e.get("id") for e in entries]
        if len(ids) != len(set(ids)):
            problems.append("%s repeats an id: %s" % (names[key], sorted(
                {i for i in ids if ids.count(i) > 1})[:5]))
        if ids != sorted(ids):
            problems.append("%s is not sorted by id" % names[key])
        for e in entries:
            problems.extend(_entry_findings(e, names[key], kinds,
                                            allowed_docs, digests, prefixes))
        expected = _counts([e for e in entries if isinstance(e, dict)
                            and "rights_status" in e and "kind" in e], kinds)
        if doc.get("counts") != expected:
            problems.append("%s states counts %r; its entries give %r"
                            % (names[key], doc.get("counts"), expected))
        if key != "brm":
            used = {e.get("document") for e in entries}
            listed_docs = {d.get("evidence") for d in doc.get("documents")
                           or []}
            if used != listed_docs:
                problems.append("%s lists documents %s but its entries come "
                                "from %s" % (names[key], sorted(listed_docs),
                                             sorted(used)))
    if docs["capabilities"].get("homonym_note") != HOMONYM_NOTE:
        problems.append("%s has lost its homonym note (E5)"
                        % names["capabilities"])

    # FIBF-2 a, as a negative check over every data value.
    for key in ("brm", "functions", "capabilities", "snapshot"):
        for path, value in _walk_values(docs[key]):
            if THIRD_PARTY.search(value):
                problems.append("%s%s names third-party mapping material "
                                "(FIBF-2 a): %r" % (names[key], path,
                                                    value[:80]))

    if contents[names["notice"]] != notice_text(pinned):
        problems.append("%s is not what %s writes from %s. Was it edited by "
                        "hand, or a pin changed without --rebuild?"
                        % (names["notice"], GENERATOR, PINS))
    guard = harvest_bpo_module(base)
    problems.extend(guard.admission_findings(base, pinned["directory"],
                                             contents))
    return problems


def check(base: Path | None = None) -> tuple[list[str], dict]:
    base = base or root()
    pinned = pins(base)
    names = outputs(pinned)
    contents = {}
    for path in names.values():
        if (base / path).is_file():
            contents[path] = (base / path).read_bytes()
    problems = check_documents(pinned, contents, base)
    summary = {}
    if not problems:
        for key in ("brm", "functions", "capabilities", "snapshot"):
            summary[key] = parse_yaml(contents[names[key]])["counts"]
    return problems, summary


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--rebuild", action="store_true",
                    help="harvest the pinned documents (cache first) and "
                         "rewrite the outputs")
    ap.add_argument("--confirm", action="store_true",
                    help="refetch every pinned document, harvest in memory "
                         "and require byte-identical outputs")
    ap.add_argument("--cache", default=None,
                    help="document cache (default .upstream-cache/i2a/)")
    args = ap.parse_args(argv)
    base = root()
    cache = Path(args.cache) if args.cache else base / CACHE

    if args.rebuild or args.confirm:
        built, evidence = build(cache, base, refetch=args.confirm)
        for finding in evidence["findings"]:
            print("  note: %s" % finding)
        differing = sorted(path for path, data in built.items()
                           if not (base / path).is_file()
                           or (base / path).read_bytes() != data)
        if args.confirm:
            if differing:
                print("  FINDING: %d output(s) are not what harvesting the "
                      "pinned documents produces: %s"
                      % (len(differing), ", ".join(differing)))
                return 1
            print("  every federal inventory output is byte-identical to a "
                  "fresh harvest of the refetched documents")
            return 0
        for path, data in sorted(built.items()):
            target = base / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            print("  wrote %s%s" % (path, "" if path in differing
                                    else " (unchanged)"))

    problems, summary = check(base)
    if problems:
        for problem in problems:
            print("  FINDING: %s" % problem)
        return 1
    b, f, c, s = (summary["brm"], summary["functions"],
                  summary["capabilities"], summary["snapshot"])
    print("  ok: BRM %d entries (%d mission sectors, %d business functions, "
          "%d services); FIBF %d functions, %d activities, %d business "
          "capabilities (%d with text withheld); snapshot %d documents (%d "
          "harvested, %d withheld-mitre, %d withheld-ambiguous); digests "
          "match rights.yaml, no third-party mapping text, admission guard "
          "holds, NOTICE-federal.md is fresh"
          % (b["entries"], b[KIND_SECTOR], b[KIND_BRM_FUNCTION],
             b[KIND_BRM_SERVICE], f[KIND_FUNCTION], f[KIND_ACTIVITY],
             c[KIND_CAPABILITY], f["text_withheld"] + c["text_withheld"],
             s["documents"], s[STATUS_HARVESTED], s[STATUS_MITRE],
             s[STATUS_AMBIGUOUS]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
