def _entry(prefix, doc, code, kind, row=None):
    token = doc["token"]
    part = code if code else "row%d" % row
    if code and row is not None:
        part = "%s-r%d" % (code, row)
    return "%s-%s-%s-%s" % (prefix, token, part, kind)


def doc_token(evidence_id: str) -> str:
    return evidence_id.replace("fibf-doc-", "").replace(
        "fibf-page-", "PAGE-").upper()


def harvest_table(book, spec, doc, withhold, counter):
    """(functions, activities, capabilities, located rows) from one table."""
    sheet = book.sheet(spec["sheet"])
    if sheet is None:
        raise Refused("%s has no sheet %r" % (doc["id"], spec["sheet"]))
    hr = spec["header_row"]
    for letter, expected in spec["check"].items():
        got = clean(sheet.cells.get(hr, {}).get(column_number(letter)))
        if (got or "").casefold() != expected.casefold():
            raise Refused("%s sheet %r cell %s%d reads %r, not %r: the table "
                          "moved, so SPECS no longer describes it"
                          % (doc["id"], spec["sheet"], letter, hr, got,
                             expected))
    col = {role: column_number(letter)
           for role, letter in spec["columns"].items()}
    rows = sorted(r for r in sheet.cells if r > hr)
    functions, activities, capabilities = [], [], []
    seen_functions = {}
    last_function = None
    common = {"register": doc["register"], "document": doc["id"],
              "document_sha256": doc["sha256"], "domain": doc["domain"],
              "draft": doc["draft"]}

    def text(r, role):
        return clean(sheet.cells[r].get(col[role])) if role in col else None

    for r in rows:
        if "function" in col:
            f_code, f_name = split_code(text(r, "function"))
        else:
            f_code, f_name = text(r, "function_code"), text(r, "function_name")
        parent_from = "row"
        if f_code is None and f_name is None:
            # A blank function cell in a functions-and-activities list is
            # the list's grouping layout (the function is printed once,
            # above its activities), recorded as `cell-above`. In a
            # capability table a blank stays blank.
            if spec["component"] == FA and last_function:
                f_code, f_name = last_function
                parent_from = "cell-above"
            else:
                parent_from = None
        else:
            last_function = (f_code, f_name)
        if "activity" in col:
            a_code, a_name = split_code(text(r, "activity"))
        else:
            a_code, a_name = (text(r, "activity_code"),
                              text(r, "activity_name"))
        locator = {"sheet": sheet.name, "row": r}

        if spec["component"] == FA:
            if f_code and parent_from == "row" and (f_code, f_name) \
                    not in seen_functions:
                seen_functions[(f_code, f_name)] = r
                functions.append(dict(
                    kind=KIND_FUNCTION, code=f_code, parent_code=None,
                    name=withhold.field(f_name, counter), description=None,
                    locator=locator, **common))
            description = text(r, "activity_description")
            if a_code is None and a_name is None and description is None:
                continue
            activities.append(dict(
                kind=KIND_ACTIVITY, code=a_code, parent_code=f_code,
                parent_from=parent_from,
                name=withhold.field(a_name, counter),
                description=withhold.field(description, counter),
                locator=locator, **common))
        else:
            statement = text(r, "statement")
            c_code = text(r, "capability_code")
            if statement is None and c_code is None:
                continue
            capabilities.append(dict(
                kind=KIND_CAPABILITY, code=c_code, parent_code=a_code,
                function_code=f_code, ipo=text(r, "ipo"), name=None,
                description=withhold.field(statement, counter),
                locator=locator, homonym_flag=True, **common))
    return functions, activities, capabilities, (sheet.name, hr, rows)


def assign_ids(entries: list[dict], prefix: str) -> None:
    """Ids from (document, code, kind); a code repeated in one document and
    kind takes its row, so no two entries collapse into one."""
    seen = {}
    for e in entries:
        seen.setdefault((e["document"], e["code"], e["kind"]), []).append(e)
    for (doc, code, kind), group in seen.items():
        for e in group:
            position = None
            if len(group) > 1 or code is None:
                position = e["locator"].get("row",
                                            e["locator"].get("html_line"))
            e["id"] = _entry(prefix, {"token": doc_token(doc)}, code, kind,
                             position)
            if len(group) > 1 and code is not None:
                e["code_repeated_in_document"] = True


EEO_BUTTON = re.compile(
    r'<button class="usa-accordion__button"[^>]*aria-controls="([^"]+)"[^>]*>'
    r"\s*([^<]*?)\s*</button>")


def harvest_eeo(data: bytes, doc: dict, withhold, counter) -> tuple:
    """The EEO page's functions: the accordion buttons inside
    #eeo-lifecycle. Returns (functions, observations)."""
    text = data.decode("utf-8")
    start = text.find('id="eeo-lifecycle"')
    if start < 0:
        raise Refused("the EEO page has no #eeo-lifecycle block")
    end = text.find('id="capabilities"', start)
    block_end = end if end > 0 else len(text)
    functions = []
    for m in EEO_BUTTON.finditer(text, start, block_end):
        code, name = split_code(html.unescape(m.group(2)))
        if code is None:
            continue
        line = text.count("\n", 0, m.start()) + 1
        functions.append(dict(
            kind=KIND_FUNCTION, code=code, parent_code=None,
            name=withhold.field(name, counter), description=None,
            locator={"html_line": line, "element": m.group(1)},
            register=doc["register"], document=doc["id"],
            document_sha256=doc["sha256"], domain=doc["domain"],
            draft=doc["draft"]))
    bodies = re.findall(r'<table id="(eeo-[^"]+)"[^>]*>.*?<tbody>(.*?)</tbody>',
                        text[start:], re.S)
    empty = [tid for tid, body in bodies if not body.strip()]
    observations = []
    if bodies and len(empty) == len(bodies):
        observations.append(
            "Every activity table and the business capability table is empty "
            "in the pinned bytes (%d tables): the page fills them in the "
            "browser from a resource that is not pinned, so only the "
            "functions are harvested." % len(bodies))
    return functions, observations


def harvest_fibf(pinned: dict, read: Bytes) -> dict:
    """Every FIBF output's data, from the pinned bytes."""
    source = pinned["fibf"]
    prefix = source["entry_prefix"]
    books, rights, pages = {}, {}, {}
    for item in source["items"]:
        data = read(item)
        if item["url"].endswith((".xlsx", ".xlsm")):
            books[item["id"]] = Workbook(data)
            rights[item["id"]] = workbook_rights(books[item["id"]])
        else:
            rights[item["id"]] = html_rights(data)
        page = source["pages"].get(item.get("domain"))
        pages[item["id"]] = read(page) if page else None

    status = {}
    findings = []
    for item in source["items"]:
        r = rights[item["id"]]
        in_yaml = item["id"] in source["mitre_marked"]
        in_bytes = bool(r["mitre_parts"])
        if in_yaml and in_bytes:
            status[item["id"]] = STATUS_MITRE
        elif in_yaml or in_bytes or r["other_notices"]:
            status[item["id"]] = STATUS_AMBIGUOUS
            findings.append("%s: rights.yaml MITRE notice %s, bytes MITRE %s, "
                            "other notices %s -- treated as restricted"
                            % (item["id"], in_yaml, in_bytes,
                               r["other_notices"]))
        else:
            status[item["id"]] = STATUS_HARVESTED

    withheld_books = [books[i] for i, s in status.items()
                      if s != STATUS_HARVESTED and i in books]
    texts = mitre_texts(withheld_books)

    functions, activities, capabilities, documents = [], [], [], []
    content = {}
    for item in source["items"]:
        doc = {"id": item["id"], "sha256": item["sha256"],
               "register": source["register"], "domain": item.get("domain"),
               "token": doc_token(item["id"])}
        book = books.get(item["id"])
        r = rights[item["id"]]
        media = (item["url"].rsplit(".", 1)[-1] if book is not None
                 else "html")
        basis = draft_basis(book, item, pages[item["id"]])
        doc["draft"] = bool(basis)
        record = {"evidence": item["id"], "url": item["url"],
                  "sha256": item["sha256"], "bytes": item["bytes"],
                  "domain": item.get("domain"),
                  "components": list(item.get("components") or []),
                  "media": media, "status": status[item["id"]]}
        validation = {
            "rights_yaml_mitre_notice": item["id"] in source["mitre_marked"],
            "mitre_notice_in_bytes": bool(r["mitre_parts"]),
            "other_notice_in_bytes": bool(r["other_notices"])}
        record["rights_validation"] = validation
        record["draft"] = {"value": doc["draft"], "basis": basis}
        if book is not None:
            content[item["id"]] = sha256("\n".join(
                "%s|%d|%d|%s" % (s.name.strip(), r_, c, v)
                for s in book.sheets for r_ in sorted(s.cells)
                for c, v in sorted(s.cells[r_].items())).encode("utf-8"))
        if status[item["id"]] != STATUS_HARVESTED:
            documents.append(record)
            continue

        validation["external_links_to_mitre_host"] = \
            r["external_links_to_mitre_host"]
        counter = {}
        withhold = Withholding(texts)
        harvested_sheets, observations = [], []
        f, a, c = [], [], []
        if book is None:
            f, observations = harvest_eeo(read(item), doc, withhold, counter)
            record["edition"] = None
            record["excluded_fibf_2a"] = []
            record["not_harvested_sheets"] = []
            harvested_sheets.append({"page_block": "#eeo-lifecycle",
                                     "component": FA})
        else:
            specs = SPECS.get(item["id"])
            if specs is None:
                raise Refused("%s is harvestable and SPECS does not say how to "
                              "read it" % item["id"])
            specs = specs(item["id"])
            read_columns = {(spec["sheet"], column_number(letter))
                            for spec in specs
                            for letter in spec["columns"].values()}
            excluded, third = third_party_columns(book, item["id"],
                                                  read_columns)
            withhold.third = third
            record["edition"] = edition(book)
            record["excluded_fibf_2a"] = excluded
            read_sheets = set()
            for spec in specs:
                f1, a1, c1, (name, hr, rows) = harvest_table(
                    book, spec, doc, withhold, counter)
                f += f1
                a += a1
                c += c1
                read_sheets.add(name)
                harvested_sheets.append({
                    "sheet": name, "component": spec["component"],
                    "header_row": hr,
                    "rows": [rows[0], rows[-1]] if rows else None,
                    "columns": dict(sorted(spec["columns"].items(),
                                           key=lambda kv: kv[1]))})
            record["not_harvested_sheets"] = [
                {"sheet": s.name, "hidden": s.state is not None,
                 "why": sheet_reason(s)}
                for s in book.sheets if s.name not in read_sheets]
        record["harvested"] = harvested_sheets
        record["entries"] = {KIND_FUNCTION: len(f), KIND_ACTIVITY: len(a),
                             KIND_CAPABILITY: len(c)}
        record["withheld_fields"] = dict(sorted(counter.items()))
        if observations:
            record["observations"] = observations
        functions += f
        activities += a
        capabilities += c
        documents.append(record)

    # Duplicates (FIBF-3 a): workbooks whose every cell is identical,
    # recorded both ways, never merged.
    by_content = {}
    for doc_id, digest in content.items():
        by_content.setdefault(digest, []).append(doc_id)
    for record in documents:
        twins = [d for d in by_content.get(content.get(record["evidence"]), [])
                 if d != record["evidence"]]
        record["duplicate_of"] = twins

    fa = functions + activities
    assign_ids(fa, prefix)
    assign_ids(capabilities, prefix)
    for e in fa + capabilities:
        withheld = any(isinstance(e.get(k), dict) for k in ("name",
                                                            "description"))
        e["rights_status"] = RIGHTS_STATUS_PARTIAL if withheld \
            else RIGHTS_STATUS
    return {"documents": documents, "fa": order(fa), "caps": order(capabilities),
            "findings": findings, "mitre_texts": texts}


ENTRY_KEYS = ("id", "kind", "register", "document", "document_sha256",
              "domain", "code", "level", "parent_code", "parent_from",
              "function_code", "ipo", "name", "description", "locator",
              "draft", "code_repeated_in_document", "homonym_flag",
              "mission_sector_as_stated", "business_function_as_stated",
              "rights_status")


def order(entries: list[dict]) -> list[dict]:
    out = []
    for e in sorted(entries, key=lambda x: x["id"]):
        e = dict(e, level=LEVELS[e["kind"]])
        out.append({k: e[k] for k in ENTRY_KEYS if k in e})
    return out


