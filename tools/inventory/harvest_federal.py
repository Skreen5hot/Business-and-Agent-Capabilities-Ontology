"""Harvest the federal catalogs into the Capability Term Inventory (Phase I-2c).

    python tools/inventory/harvest_federal.py             # offline check
    python tools/inventory/harvest_federal.py --rebuild   # read the pinned bytes, rewrite
    python tools/inventory/harvest_federal.py --confirm   # refetch, harvest, compare

FEAF-II BRM 3.1 and FIBF, under the architect's decisions of 2026-10-28
(docs/decisions/2026-10-28-i2a-decided.md: BRM-1 a, BRM-2 c, FIBF-1 c,
FIBF-2 a, FIBF-3 a; docs/decisions/2026-10-28-i2-and-bpo-repin-decided.md:
E1, E5, E6 and part C). The pins are config/inventory-federal-sources.yaml,
which names evidence items whose URL and sha256 are in
docs/sources/inventory/rights.yaml (I-2a); this tool reads the digests from
there and never restates them.

WHAT THE INVENTORY IS, AND IS NOT

Source evidence (scope approval D6), as in Phase I-1: one entry per source
item, with the document, its digest and a locator (sheet and row, page, or
HTML line). Nothing is vocabulary, admitted, grouped, triaged or merged
(Amendment 2, Amendment 4; I-4 does the rest). Two documents saying the
same thing are two sets of entries; a code repeated inside one document is
two entries, each with its row. A FIBF Business Capability is recorded in
FIBF's own meaning -- an outcome-based requirement record tied to
authoritative references -- with a homonym flag, neither equated with nor
excluded from BCO's organization-borne capability (E5).

THE OUTPUTS (docs/sources/inventory/)

  feaf-brm-entries.yaml          both BRM documents, kept apart (BRM-2 c):
                                 the service codes and definitions table
                                 (`brm-service`, INV-FEAF-BRM-SCD-...) and
                                 the taxonomy appendix (`brm-mission-sector`,
                                 `brm-business-function`, `brm-service`,
                                 INV-FEAF-BRM-TAX-...), levels named as the
                                 BRM names them.
  fibf-entries.yaml              `fibf-function`, `fibf-activity`.
  fibf-business-capabilities.yaml  `fibf-business-capability`.
  fibf-snapshot.yaml             every pinned FIBF document (FIBF-3 a), with
                                 its status, draft and duplicate findings and
                                 the columns excluded under FIBF-2 a.
  NOTICE-federal.md              the attribution. A file of its own because
                                 docs/sources/inventory/NOTICE.md is I-1's,
                                 regenerated byte for byte by harvest_bpo.py
                                 and recorded by digest in I-1's approval;
                                 adding to it would change approved bytes.

WHICH FIBF DOCUMENTS ARE PUBLISHED

The architect decided the posture; this tool applies it document by
document, from rights.yaml and from the bytes, and refuses to trust either
alone. A workbook is harvested only when all of these hold:

  - rights.yaml records no MITRE notice for it (FIBF-1 c);
  - no XML part of it contains "MITRE", other than the targets of external
    workbook links (a link's target is a path, not a notice, and it is
    counted in the snapshot instead);
  - no header, footer, drawing, document property or cell text of it
    carries a copyright sign, "copyright", "all rights reserved",
    "licensed under" or "proprietary notice". Printer-settings parts are
    binary driver records (an HP driver's own copyright string is in
    several) and are not document text, so they are not read.

A workbook rights.yaml marks is `withheld-mitre`. A workbook rights.yaml
does not mark but whose bytes fail a test above is `withheld-ambiguous`:
the two sources of evidence disagree, so the conservative reading wins and
the snapshot says so. A withheld document appears in the snapshot by
locator and digest only -- no name, code, description or count of its
content.

Inside a harvested document, two rules withhold a field's text, keeping
the field and its code with `{withheld: <reason>}`:

  text-in-mitre-marked-document  the normalised text (case and punctuation
                                 ignored, two words or more) equals a cell
                                 of a withheld MITRE-marked workbook: the
                                 same words are not published from a second
                                 file (I-1's shared-text rule, applied to
                                 FIBF-1 c);
  third-party-mapping-text       the text names ITIL, TBM, AXELOS,
                                 PeopleCert or Technology Business
                                 Management (two words or more), or equals
                                 a cell of a FIBF-2 a mapping column or
                                 sheet in the same document.

Codes are identifiers and are kept, including a code that also appears in
a withheld workbook: an identifier printed in a clearly redistributable
document is that document's content. A mapping column -- one whose header
names ITIL or TBM, or at least half of whose cells do, and the declared
TBM cost-categorization sheet -- is never read into entries; nor is any
column outside an entry's shape (authoritative references, comments,
counts). The snapshot lists, by sheet and column letter, every column in
which ITIL or TBM is named, whether it is a mapping column, and whether it
was read (a harvested column that merely mentions one, such as an activity
named after TBM, keeps its other cells; the naming cell is withheld).

HOW THE BYTES ARE READ

Workbooks (.xlsx, and the grants .xlsm) are read with zipfile as data:
shared strings (ElementTree), and each cell element that has content,
found by a pattern over its sheet part and parsed as XML -- some sheets
are 40 MB of empty styled cells, which a whole-part parse takes ten
seconds over. Inline strings and cached formula values are read as
written; merged ranges carry their top-left value. Macros are never opened,
let alone run. Which sheet and which columns hold what is declared per
document in SPECS below and the header cells are checked against it, so a
republished workbook with moved columns is a refusal, not a silent
mis-harvest.

The EEO domain publishes its functions only in its page's HTML (pinned in
rights.yaml); they are read from the static markup, with the line number
as locator. Its activity and business-capability tables are empty in the
pinned bytes (filled in the browser from a resource that is not pinned),
so nothing is harvested from them, and the snapshot says so.

The BRM PDFs are read with pypdf (pinned in requirements-dev.txt; BSD-3-
Clause, pure Python), used only to parse the PDF objects and content
streams. Text extraction is this tool's own: every glyph is placed by
following the text-positioning operators and the font's widths, decoded
by the font's WinAnsi encoding or ToUnicode map, then assigned to a table
column by its position. A table row is found from the layout the document
uses: in the service codes table and in some taxonomy sections every cell
is centred on the code's line, elsewhere the code starts the row.
pypdf's own text extraction was tried first and is not used: it runs the
last word of a service name into the first word of its definition when
they share a line, and its layout mode gives up on the rotated pages.
Hand transcription was the other alternative (a page locator on every
row, checked); measured on these two files, positional extraction
recovers every row with no residue (a line no row claims is a refusal),
and a reviewer can re-run it, which a transcription cannot offer. Every
BRM entry carries its page.

THE OFFLINE CHECK (default; CI)

Refuses: outputs whose recorded digests are not rights.yaml's for the
documents the pins name; a snapshot that does not list exactly the
rights.yaml candidates; an entry from a document the snapshot does not
mark harvested; an entry missing a field, of an unknown kind, with an id
that its own fields do not produce, without a locator, or with text in a
withheld field; a capability without its homonym flag; counts that
disagree with the entries; a MITRE-marked document in the snapshot
carrying any key beyond its locator, digest and status; any data value
naming ITIL, TBM, AXELOS, PeopleCert or Technology Business Management; a
stale NOTICE-federal.md; and the admission guard over the whole directory
(tools/inventory/harvest_bpo.py's: no file but YAML or Markdown, no RDF,
no IRI in AUTHORED_NAMESPACES, no ratification or vocabulary key).

--rebuild and --confirm also check, against the bytes, that no harvested
text equals text in a withheld MITRE-marked workbook. --rebuild reads the
cache (.upstream-cache/i2a/, named by sha256; a missing file is fetched
from its pinned URL and must match its digest). --confirm always
refetches -- only from ussm.gsa.gov, www.gsa.gov and obamawhitehouse.archives.gov --
and requires byte-identical outputs: a moved digest is a new edition for
the architect, never a re-pin.

DETERMINISM

Entries are sorted by id; documents keep rights.yaml's order. YAML is
written by PyYAML with a fixed key order, as bytes, so LF everywhere.
"""

