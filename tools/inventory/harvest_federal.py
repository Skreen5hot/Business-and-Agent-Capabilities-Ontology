class Refused(SystemExit):
    """A question for whoever wrote the pin, the spec or the output."""


def root() -> Path:
    return layout.repository_root()


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


_PARSED = {}


def parse_yaml(data):
    """yaml.safe_load (libyaml's loader where PyYAML has it), remembered by
    the digest of the text: the entries files are megabytes, and a check
    that reads unchanged bytes twice should not pay twice. Callers treat
    the result as read-only."""
    import yaml

    raw = data.encode("utf-8") if isinstance(data, str) else data
    key = sha256(raw)
    if key not in _PARSED:
        loader = getattr(yaml, "CSafeLoader", yaml.SafeLoader)
        _PARSED[key] = yaml.load(data, Loader=loader)
    return _PARSED[key]


def norm(text: str) -> str:
    """Case, punctuation and spacing ignored: the comparison key."""
    return " ".join(re.sub(r"[^\w]+", " ", text.casefold()).split())


def clean(value) -> str | None:
    """A cell or extracted string as published, with its whitespace
    (line breaks, non-breaking spaces, runs) collapsed to single spaces."""
    if value is None:
        return None
    text = " ".join(str(value).split())
    return text or None


