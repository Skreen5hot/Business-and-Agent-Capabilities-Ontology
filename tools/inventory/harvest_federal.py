def _load_yaml(path: Path, name: str):
    if not path.is_file():
        raise Refused("%s is missing. What would say which bytes the "
                      "inventory was built from?" % name)
    return parse_yaml(path.read_bytes().decode("utf-8")) or {}


def pins(base: Path | None = None) -> dict:
    """The pins, joined to rights.yaml's evidence, checked.

    Returns {"raw": config, "brm": source, "fibf": source}; each source
    gains `items` (evidence dicts, rights.yaml order) and the FIBF source
    `pages` (the domain pages, by domain) and `mitre_marked` (the ids
    rights.yaml records a MITRE notice for).
    """
    base = base or root()
    raw = _load_yaml(base / PINS, PINS)
    for key in ("directory", "rights", "decisions", "sources"):
        if not raw.get(key):
            raise Refused("%s declares no %r" % (PINS, key))
    for record in raw["decisions"]:
        if not (base / record).is_file():
            raise Refused("%s cites decision record %s, which does not exist"
                          % (PINS, record))
    rights = _load_yaml(base / raw["rights"], raw["rights"])
    by_source = {s.get("id"): s for s in rights.get("sources") or []}
    sources = {s.get("id"): dict(s) for s in raw["sources"]}
    if set(sources) != {BRM_ID, FIBF_ID}:
        raise Refused("%s pins sources %s; this tool harvests exactly %s and %s"
                      % (PINS, sorted(sources), BRM_ID, FIBF_ID))
    for sid, source in sources.items():
        for key in ("register", "rights_record", "project", "licence",
                    "outputs"):
            if not source.get(key):
                raise Refused("%s source %s declares no %r" % (PINS, sid, key))
        record = by_source.get(source["rights_record"])
        if record is None:
            raise Refused("%s source %s names rights record %r, which %s does "
                          "not hold" % (PINS, sid, source["rights_record"],
                                        raw["rights"]))
        if record.get("register") != source["register"]:
            raise Refused("%s source %s is register %s; %s says %s"
                          % (PINS, sid, source["register"], raw["rights"],
                             record.get("register")))
        if record.get("status") != "evidence-complete":
            raise Refused("%s: rights record %s is %r, not evidence-complete; "
                          "I-2c harvests only what I-2a settled"
                          % (PINS, record["id"], record.get("status")))
        evidence = {e["id"]: e for e in record.get("evidence") or []}
        for item in evidence.values():
            if not HEX64.match(str(item.get("sha256", ""))):
                raise Refused("%s evidence %s has no sha256" % (raw["rights"],
                                                                item["id"]))
        source["evidence"] = evidence
        source["record"] = record
        for ref in source.get("context") or []:
            if ref not in evidence:
                raise Refused("%s source %s cites context %r, not in %s"
                              % (PINS, sid, ref, raw["rights"]))
    brm, fibf = sources[BRM_ID], sources[FIBF_ID]
    brm["items"] = []
    for doc in brm.get("documents") or []:
        if doc.get("evidence") not in brm["evidence"]:
            raise Refused("%s names BRM document %r, not in %s"
                          % (PINS, doc.get("evidence"), raw["rights"]))
        item = dict(brm["evidence"][doc["evidence"]])
        item["entry_prefix"] = doc["entry_prefix"]
        brm["items"].append(item)
    if len(brm["items"]) != 2:
        raise Refused("BRM-2 c harvests both BRM documents; %s names %d"
                      % (PINS, len(brm["items"])))
    fibf["items"] = [dict(e) for e in fibf["record"]["evidence"]
                     if e.get("snapshot") == fibf.get("snapshot")]
    if not fibf["items"]:
        raise Refused("rights.yaml marks no FIBF evidence %r"
                      % fibf.get("snapshot"))
    fibf["pages"] = {e["domain"]: e for e in fibf["record"]["evidence"]
                     if e["id"].startswith("fibf-page-") and e.get("domain")}
    fibf["mitre_marked"] = {e["id"] for e in fibf["items"]
                            if "MITRE" in (e.get("notices") or "")}
    raw["brm"], raw["fibf"] = brm, fibf
    raw["base"] = base
    return raw


def outputs(pinned: dict) -> dict[str, str]:
    brm, fibf = pinned["brm"]["outputs"], pinned["fibf"]["outputs"]
    if brm["notice"] != fibf["notice"]:
        raise Refused("the two sources name different notices; one tool, one "
                      "notice")
    names = {"brm": brm["entries"][0], "functions": fibf["entries"][0],
             "capabilities": fibf["entries"][1], "snapshot": fibf["snapshot"],
             "notice": brm["notice"]}
    for path in names.values():
        if not path.startswith(pinned["directory"] + "/"):
            raise Refused("%s writes %s outside %s" % (PINS, path,
                                                       pinned["directory"]))
    return names


# ----------------------------------------------------------------- bytes


def _host(url: str) -> str:
    return urllib.parse.urlsplit(url).hostname or ""


def fetch(url: str) -> bytes:
    if not url.startswith("https://") or _host(url) not in FETCH_HOSTS:
        raise Refused("refusing to fetch %s: not https on %s"
                      % (url, ", ".join(FETCH_HOSTS)))
    request = urllib.request.Request(url, headers={
        "User-Agent": "bco-inventory-federal (+%s)" % GENERATOR})
    with urllib.request.urlopen(request, timeout=180) as response:
        return response.read()


class Bytes:
    """The pinned documents, by evidence id, digest checked on every read.

    From the cache unless `refetch`, when every document comes from its
    pinned URL (and the cache is refreshed).
    """

    def __init__(self, cache: Path, refetch: bool = False):
        self.cache = cache
        self.refetch = refetch
        self.read = {}

    def __call__(self, item: dict) -> bytes:
        key = item["sha256"]
        if key in self.read:
            return self.read[key]
        path = self.cache / key
        data = None
        if not self.refetch and path.is_file():
            data = path.read_bytes()
            if sha256(data) != key:
                data = None
        if data is None:
            data = fetch(item["url"])
            if sha256(data) != key:
                raise Refused(
                    "%s served bytes digesting to %s; rights.yaml pins %s for "
                    "%s. A moved digest is a new edition for the architect, "
                    "not a re-pin." % (item["url"], sha256(data), key,
                                       item["id"]))
            self.cache.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        self.read[key] = data
        return data


# ------------------------------------------------------------- workbooks

_M = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"
_R = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"
_A = "{http://schemas.openxmlformats.org/drawingml/2006/main}"


_CELL = re.compile(r"<c\s([^>]*?)(?:/>|>((?:(?!</c>).)+)</c>)", re.S)
_ATTR = re.compile(r'(?<![\w:])([a-z]+)="([^"]*)"')
_MERGE = re.compile(r'<mergeCell ref="([A-Z]+\d+:[A-Z]+\d+)"')
_HEADER_FOOTER = re.compile(
    r"<(?:odd|even|first)(?:Header|Footer)>([^<]*)</(?:odd|even|first)"
    r"(?:Header|Footer)>")
#: Excel's header and footer field codes: sections, page fields, fonts.
_FIELD_CODES = re.compile(r'&(?:"[^"]*"|\d+|[A-Za-z])')


def column_number(letters: str) -> int:
    n = 0
    for ch in letters:
        n = n * 26 + ord(ch) - 64
    return n


def column_letters(n: int) -> str:
    out = ""
    while n:
        n, rem = divmod(n - 1, 26)
        out = chr(65 + rem) + out
    return out


def _cell_ref(ref: str) -> tuple[int, int]:
    m = re.match(r"^([A-Z]+)(\d+)$", ref)
    return int(m.group(2)), column_number(m.group(1))


class Workbook:
    """A workbook read as data. Sheets keep the workbook's order.

    sheet.cells is {row: {column: text}}, with merged ranges filled from
    their top-left cell; sheet.state is None or "hidden"/"veryHidden";
    sheet.header_footer is the text of every header and footer element.
    """

    class Sheet:
        def __init__(self, name, part, state, cells, header_footer):
            self.name, self.part, self.state = name, part, state
            self.cells, self.header_footer = cells, header_footer

    def __init__(self, data: bytes):
        self.zip = zipfile.ZipFile(io.BytesIO(data))
        names = set(self.zip.namelist())
        shared = []
        if "xl/sharedStrings.xml" in names:
            for si in ElementTree.fromstring(
                    self.zip.read("xl/sharedStrings.xml")).findall(_M + "si"):
                shared.append(self._string(si))
        book = ElementTree.fromstring(self.zip.read("xl/workbook.xml"))
        rels = {r.get("Id"): r.get("Target") for r in ElementTree.fromstring(
            self.zip.read("xl/_rels/workbook.xml.rels"))}
        self.sheets = []
        for sheet in book.find(_M + "sheets"):
            target = rels[sheet.get(_R + "id")]
            part = (target.lstrip("/") if target.startswith("/")
                    else "xl/" + target)
            self.sheets.append(self._sheet(sheet.get("name"), part,
                                           sheet.get("state"), shared))

    @staticmethod
    def _string(si) -> str:
        """A shared or inline string's text, without phonetic runs."""
        parts = []
        for child in si:
            if child.tag == _M + "t":
                parts.append(child.text or "")
            elif child.tag == _M + "r":
                for t in child.iter(_M + "t"):
                    parts.append(t.text or "")
        return "".join(parts)

    def _sheet(self, name, part, state, shared):
        # A cell is read from its own element, found by a pattern over the
        # part's text rather than by parsing the whole part: some of these
        # sheets are 40 MB of empty, styled cells, which a full parse takes
        # ten seconds over. Each cell with content is then parsed as XML.
        text = self.zip.read(part).decode("utf-8")
        cells = {}
        for m in _CELL.finditer(text):
            if m.group(2) is None:
                continue
            attrs = dict(_ATTR.findall(m.group(1)))
            element = ElementTree.fromstring("<c>%s</c>" % m.group(2))
            kind = attrs.get("t")
            v = element.find("v")
            if kind == "s" and v is not None:
                value = shared[int(v.text)]
            elif kind == "inlineStr":
                is_ = element.find("is")
                value = "".join(t.text or "" for t in is_.iter("t")
                                if is_ is not None) if is_ is not None                     else ""
            elif v is not None:
                value = v.text or ""
            else:
                continue
            if value.strip():
                r, col = _cell_ref(attrs["r"])
                cells.setdefault(r, {})[col] = value
        for ref in _MERGE.findall(text):
            first, last = ref.split(":")
            (r1, c1), (r2, c2) = _cell_ref(first), _cell_ref(last)
            value = cells.get(r1, {}).get(c1)
            if value is None:
                continue
            for r in range(r1, r2 + 1):
                for col in range(c1, c2 + 1):
                    cells.setdefault(r, {}).setdefault(col, value)
        header_footer = [html.unescape(x) for x in _HEADER_FOOTER.findall(text)]
        return self.Sheet(name, part, state, cells, header_footer)

    def sheet(self, name: str):
        for sheet in self.sheets:
            if sheet.name == name:
                return sheet
        return None

    def parts(self):
        return self.zip.namelist()

    def drawing_text(self) -> list[str]:
        out = []
        for name in self.parts():
            if name.startswith("xl/drawings/") and name.endswith(".xml"):
                root = ElementTree.fromstring(self.zip.read(name))
                out.extend(t.text or "" for t in root.iter(_A + "t"))
        return out

    def properties_text(self) -> str:
        out = []
        for name in ("docProps/core.xml", "docProps/app.xml",
                     "docProps/custom.xml"):
            if name in self.parts():
                root = ElementTree.fromstring(self.zip.read(name))
                out.extend(x.text or "" for x in root.iter())
        return " ".join(out)


def workbook_rights(book: "Workbook") -> dict:
    """What the bytes say about rights: MITRE anywhere, other notices.

    External-link relationship targets are paths to the files a workbook
    once linked to; they are counted (`external_links_to_mitre_host`), not
    read as notices. Printer settings are binary driver records.
    """
    mitre_parts, external = [], 0
    for name in book.parts():
        if name.startswith("xl/printerSettings/"):
            continue
        blob = book.zip.read(name)
        if not MITRE.search(blob):
            continue
        if name.startswith("xl/externalLinks/_rels/"):
            external += len(re.findall(rb'Target="[^"]*mitre[^"]*"', blob,
                                       re.I))
        else:
            mitre_parts.append(name)
    texts = [book.properties_text()] + book.drawing_text()
    for sheet in book.sheets:
        # A printed header or footer carries Excel's field codes glued to
        # its text ("&CCopyright ..."); they are spaced out before matching.
        texts.extend(_FIELD_CODES.sub(" ", t) for t in sheet.header_footer)
        for row in sheet.cells.values():
            texts.extend(row.values())
    other = sorted({m.group(0).lower() for t in texts
                    for m in NOTICE_TEXT.finditer(t)})
    return {"mitre_parts": mitre_parts, "other_notices": other,
            "external_links_to_mitre_host": external}


def html_rights(data: bytes) -> dict:
    text = data.decode("utf-8", errors="replace")
    return {"mitre_parts": ["page"] if MITRE.search(data) else [],
            "other_notices": sorted({m.group(0).lower()
                                     for m in NOTICE_TEXT.finditer(text)}),
            "external_links_to_mitre_host": 0}


def excel_date(value) -> str | None:
    try:
        serial = float(value)
    except (TypeError, ValueError):
        return clean(value)
    return (datetime.date(1899, 12, 30)
            + datetime.timedelta(days=int(serial))).isoformat()


def edition(book: Workbook) -> dict | None:
    """The last row of the cover sheet's version history, as published."""
    cover = next((s for s in book.sheets if s.name.strip() == "Cover"), None)
    if cover is None:
        return None
    for r in sorted(cover.cells):
        row = {c: clean(v) for c, v in cover.cells[r].items()}
        cols = {v: c for c, v in row.items() if v}
        if "Date" in cols and ("Version" in cols or "Change Description"
                               in cols):
            last = None
            for r2 in sorted(x for x in cover.cells if x > r):
                values = cover.cells[r2]
                if values.get(cols["Date"]):
                    last = r2
            if last is None:
                return None
            values = cover.cells[last]
            out = {"version": clean(values.get(cols.get("Version"))),
                   "date": excel_date(values.get(cols["Date"])),
                   "locator": {"sheet": cover.name, "row": last}}
            return out
    return None


def draft_basis(book: Workbook | None, item: dict, page: bytes | None) -> list:
    """Where the bytes call a document a draft: its cover drawing, its
    document properties, or its domain page (the pinned HTML)."""
    basis = []
    if book is not None:
        if any(DRAFT.search(t) for t in book.drawing_text()):
            basis.append("cover drawing text")
        root_props = book.zip.read("docProps/core.xml") \
            if "docProps/core.xml" in book.parts() else b""
        status = re.search(rb"<cp:contentStatus>([^<]*)<", root_props)
        if status and DRAFT.search(status.group(1).decode("utf-8", "replace")):
            basis.append("document properties")
    if page is not None:
        text = html.unescape(re.sub(r"<[^>]+>", " ", page.decode(
            "utf-8", errors="replace")))
        if DRAFT.search(text):
            basis.append("domain page (rights.yaml fibf-page-%s)"
                         % item["domain"].lower().replace("fibf-", ""))
    return basis


