"""Exactly one licensing disposition per tracked file.

    python tools/licensing/disposition.py              # summary
    python tools/licensing/disposition.py --list third-party-cited
    python tools/licensing/disposition.py --check      # exit 1 on a finding

Derived from the declared role in the layout contract plus explicit owner
adjudications, never from a list of filenames. A list of filenames decays
in two directions at once: it stops matching what is there, and nothing
notices.

Every rule that matches is collected rather than the first one winning. A
first-match chain silently prefers whichever rule was written earliest,
and a later contradictory rule is never seen. Two matches is a refusal,
and so is none.

THE QUESTION THIS EXISTS TO ANSWER

Not "what licence is this" but "may this be published". Those differ
exactly where it matters. Reference material consulted while building an
ontology is cited, not redistributed, and a repository that contains it
is redistributing it whatever the README says.

There are three third-party answers here, not one. A licensed framework
may not be redistributed at all. A permissive upstream may, on condition
-- and a condition nobody checks is a condition nobody meets, so the
attribution every vendored licence requires is a check below rather than
a notice file somebody remembers to update.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path
from typing import NamedTuple

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import layout  # noqa: E402

CONTENT = "project-content"
SOFTWARE = "project-software"
CITED = "third-party-cited"
#: Third-party, redistributed, and permitted to be. The distinction from
#: CITED is the licence and not the convenience: BFO is CC BY 4.0, CCO is
#: BSD-3-Clause and BPO is MIT, and all three allow redistribution
#: provided attribution travels with the work.
VENDORED = "third-party-redistributed"

UPSTREAM_SOURCES = "config/upstream-sources.yaml"
NOTICE = "vendor/NOTICE.md"
#: The site's vendored assets (Mermaid, MIT) have their own pins and their
#: own notice, written by tools/site/vendor_assets.py. Separate from the
#: upstream ontologies' because a different tool writes them, and one
#: notice regenerated by two tools would be right only after whichever
#: ran last.
SITE_VENDOR = "config/site-vendor.yaml"
SITE_NOTICE = "vendor/site/NOTICE.md"
#: The Capability Term Inventory's pins. Each source names the entries file
#: that carries its text, the licence it carries it under, and the notice
#: tools/inventory/harvest_bpo.py writes beside it -- a third notice for a
#: third tool, for the same reason as the site's.
INVENTORY_SOURCES = "config/inventory-sources.yaml"

#: SPDX identifiers this tool can recognise in a LICENSE file. Listed
#: rather than pattern-matched, because "BSD" appears in several licences
#: that are not the same licence -- a lesson from the project this was
#: carried from, which shipped a BSD template and tested only for a
#: phrase every BSD variant contains.
KNOWN_LICENCES = (
    ("MIT License", "MIT"),
    ("Apache License", "Apache-2.0"),
    ("Creative Commons Attribution 4.0", "CC-BY-4.0"),
    ("GNU GENERAL PUBLIC LICENSE", "GPL-3.0-or-later"),
    ("Mozilla Public License", "MPL-2.0"),
)


def project_licence() -> str:
    """What this repository actually offers itself under.

    Read from LICENSE rather than written here. A hardcoded map would
    assert a licence the repository does not declare, which is the same
    class of error as a README claiming a redistribution policy the
    contents contradict.

    A content/software split -- published ontology under one licence and
    tooling under another -- is a reasonable owner decision and is what
    the project this method came from settled on. It is not assumed here:
    right now this repository says one licence for everything, and this
    reports that.
    """
    text = layout.component("licence.project").resolve().read_text(
        encoding="utf-8")
    found = [spdx for needle, spdx in KNOWN_LICENCES if needle in text]
    if len(found) != 1:
        raise Refused(
            "LICENSE names %d recognised licences (%s). Exactly one is "
            "required, because every project-authored file is reported as "
            "carrying it." % (len(found), found or "none"))
    return found[0]


def vendored_sources() -> dict:
    """Pinned upstreams, indexed by the extract path each produces.

    Read here rather than restated, so the licence this tool reports for
    a vendored file and the licence the vendoring tool wrote into that
    file come from one declaration.
    """
    import yaml

    root = layout.repository_root()
    path = root / UPSTREAM_SOURCES
    if not path.is_file():
        raise Refused(
            UPSTREAM_SOURCES + " is missing, so the licence of every "
            "vendored extract would have to be guessed from its contents.")
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    found = {}
    for entry in raw.get("sources") or []:
        for required in ("extract", "licence"):
            if not entry.get(required):
                raise Refused("a source in %s declares no %r"
                              % (UPSTREAM_SOURCES, required))
        for required in ("spdx", "attribution"):
            if not entry["licence"].get(required):
                raise Refused("%s declares no licence.%s for %s"
                              % (UPSTREAM_SOURCES, required,
                                 entry["extract"]))
        found[entry["extract"]] = entry
    return found


def site_vendored_assets() -> dict:
    """Pinned site assets, indexed by the repository path of each member.

    Read from config/site-vendor.yaml, the same declaration
    tools/site/vendor_assets.py writes the files and the notice from, so
    the licence reported here and the attribution in the notice cannot
    come from two places. Each entry carries the asset's `licence` block,
    in the shape vendored_sources() returns, so the attribution check
    treats both alike.
    """
    import yaml

    root = layout.repository_root()
    path = root / SITE_VENDOR
    if not path.is_file():
        raise Refused(
            SITE_VENDOR + " is missing, so the licence of every vendored "
            "site asset would have to be guessed from its contents.")
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    found = {}
    for entry in raw.get("assets") or []:
        licence = entry.get("licence") or {}
        for required in ("spdx", "attribution"):
            if not licence.get(required):
                raise Refused("%s declares no licence.%s for %s"
                              % (SITE_VENDOR, required, entry.get("id")))
        for member in entry.get("members") or []:
            if not member.get("path"):
                raise Refused("a member of %s in %s declares no path"
                              % (entry.get("id"), SITE_VENDOR))
            found[member["path"]] = {"licence": licence,
                                     "asset": entry.get("id")}
    return found


def inventory_sources() -> dict:
    """Inventory entries files, {path: ({"licence": ...}, notice)}.

    Read from config/inventory-sources.yaml, the same declaration the
    harvester writes the notice from. Only a source's `entries` file is
    third-party text; its findings and notice are this repository's.
    """
    import yaml

    root = layout.repository_root()
    path = root / INVENTORY_SOURCES
    if not path.is_file():
        raise Refused(
            INVENTORY_SOURCES + " is missing, so the licence of the "
            "inventory's third-party text would have to be guessed.")
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    found = {}
    for entry in raw.get("sources") or []:
        licence = entry.get("licence") or {}
        outputs = entry.get("outputs") or {}
        for required in ("spdx", "attribution"):
            if not licence.get(required):
                raise Refused("%s declares no licence.%s for %s"
                              % (INVENTORY_SOURCES, required, entry.get("id")))
        for required in ("entries", "notice"):
            if not outputs.get(required):
                raise Refused("%s declares no outputs.%s for %s"
                              % (INVENTORY_SOURCES, required, entry.get("id")))
        found[outputs["entries"]] = ({"licence": licence,
                                      "source": entry.get("id")},
                                     outputs["notice"])
    return found


def redistributed_sources() -> dict:
    """Every vendored file's pin, with the notice that must attribute it.

    {path: (entry, notice)}. Upstream extracts first, then site assets,
    then inventory entries; a path pinned twice is refused, because which
    licence it carries would depend on lookup order.
    """
    out = {path: (entry, NOTICE)
           for path, entry in vendored_sources().items()}
    for path, entry in site_vendored_assets().items():
        if path in out:
            raise Refused("%s is pinned by both %s and %s"
                          % (path, UPSTREAM_SOURCES, SITE_VENDOR))
        out[path] = (entry, SITE_NOTICE)
    for path, (entry, notice) in inventory_sources().items():
        if path in out:
            raise Refused("%s is pinned by %s and by another pin file"
                          % (path, INVENTORY_SOURCES))
        out[path] = (entry, notice)
    return out


def licence_of(disposition: str, relative=None):
    if disposition == CITED:
        return None
    if disposition == VENDORED:
        sources = redistributed_sources()
        if relative not in sources:
            raise Refused(
                "%s is declared vendored, and none of %s, %s or %s pins a "
                "source producing it, so nothing states what licence it "
                "carries." % (relative, UPSTREAM_SOURCES, SITE_VENDOR,
                              INVENTORY_SOURCES))
        return sources[relative][0]["licence"]["spdx"]
    return project_licence()

ADJUDICATIONS = "config/licensing-adjudications.yaml"

#: Roles whose files this repository authored and may publish as content.
#:
#: ARO's `registered-source` is not carried over: nothing here plays
#: that part, and a role with no file is a rule for nothing.
#:
#: `spike-artifact`: a time-boxed trial's inputs -- its schema, sample
#: data, fixtures, pinned requirements and the script that measures it
#: (trials/). Adopted from ARO on 2026-10-23 for the P2 LinkML trial,
#: the first thing here to play that part. Content under the project
#: licence, Python included, because what a trial publishes is evidence
#: for a decision rather than tooling anything runs: nothing in the
#: suite imports it. A role of its own rather than `documentation` or
#: `test-fixture` because it carries a consequence: validate.py loads
#: every `test-fixture` as Turtle, and a trial's fixtures are YAML for a
#: different validator.
#:
#: `specification`: the specification in force, v0.4.0-draft.1 today,
#: written by the architect. A role of its own rather than
#: `documentation` because it carries a consequence beyond licensing --
#: the vendoring tool reads it for the upstream terms the design names.
#: The superseded v0.3 is `documentation`, so it stops seeding the day it
#: is superseded.
#:
#: `historical-draft`: the v0.1 Turtle package under drafts/, preserved
#: byte-for-byte as it was imported. Project-authored (an earlier
#: iteration of this work), so content under the project licence, Python
#: included -- which is why it sits here rather than in SOFTWARE_ROLES.
#: A role of its own so that nothing loads its Turtle as ontology: it
#: uses a namespace v0.4 renames away from, and its defects are not this
#: corpus's defects.
#:
#: `site-source`: the public site's page fragments, curated copy,
#: stylesheet and scripts. Content rather than software, JavaScript
#: included, because the site is a published document: what it says is
#: the point, and the scripts only search and display it. The stylesheet
#: and the two scripts are carried from BFO-Aligned ValueNet, the same
#: author's project, and keep their original SPDX headers -- see
#: docs/HANDOFF.md for that open question.
#:
#: `communication`: messages to and from other teams (communications/).
#: Content under the project licence. Incoming messages are other teams'
#: words, copied verbatim -- today only BPO and ARO, which have the same
#: author as this repository. A message from a team with a different
#: owner would need its own role and rule, as cited references do.
#:
#: `conceptual-model`: the Stage 02 conceptual models
#: (src/02_conceptual_models/CM-*.md), written here under the Stage 02
#: standard. Content under the project licence, like the specification
#: they trace to. A role of its own rather than `documentation` because
#: it carries a consequence: tools/conceptual/check_models.py checks every
#: file in the role against the model format, and the site renders each
#: one on its Models page.
CONTENT_ROLES = {"ontology-module", "ontology-module-set",
                 "ontology-validation", "test-fixture", "documentation",
                 "generated-artifact", "specification", "historical-draft",
                 "site-source", "communication", "spike-artifact",
                 "conceptual-model"}

#: Roles that are software rather than published content.
SOFTWARE_ROLES = {"tool", "configuration"}

#: The repository's own terms. Content, and the file every other
#: disposition is derived from.
LICENCE_ROLES = {"project-licence"}

#: Roles this repository may not redistribute at all.
CITED_ROLES = {"third-party-reference"}

#: Roles that are somebody else work, redistributed under their terms.
#:
#: `vendored-asset`: the third-party files the public site serves --
#: Mermaid's browser bundle and its LICENSE, pinned in
#: config/site-vendor.yaml (docs/decisions/2026-10-25-stage-02-choices.md
#: chose a vendored copy over a CDN). MIT, which permits redistribution
#: with attribution; the licence is read from that pin and the attribution
#: is checked against vendor/site/NOTICE.md, exactly as the extracts' are
#: against vendor/NOTICE.md. Not `vendored-ontology`, which the validation
#: ladder, the term index and the site's upstream downloads all read as
#: Turtle.
#:
#: `source-evidence`: the Capability Term Inventory's entries files
#: (docs/sources/inventory/), which hold another project's labels and
#: definitions verbatim as evidence -- today BPO's, under MIT. Written by a
#: tool here, but the text is not this repository's, so it is classified
#: like a vendored file: the licence is read from
#: config/inventory-sources.yaml, and the attribution declared there is
#: checked against the notice that file names. Text a source took from a
#: third party whose terms are unverified (the APQC PCF) is withheld by
#: the harvester, not licensed by this rule. Not `vendored-ontology`:
#: these are YAML, and nothing that reads Turtle may select them.
VENDORED_ROLES = {"vendored-ontology", "vendored-asset", "source-evidence"}

#: Suffix rules for files no component claims. Kept small on purpose: the
#: contract is the primary authority and this is the fallback, so a
#: growing list here means the contract is being left behind.
SOFTWARE_SUFFIXES = (".py", ".cfg", ".ini", ".toml", ".yml", ".yaml")
CONTENT_SUFFIXES = (".ttl", ".md", ".html", ".css", ".svg", ".png", ".jsonld",
                    ".cff", ".txt", ".tsv", ".json")

#: Suffixless root files that are repository configuration.
CONFIG_NAMES = (".gitignore", ".gitattributes", ".nvmrc")


class Refused(SystemExit):
    """Raised rather than guessing. Every message names the file."""


class Disposition(NamedTuple):
    path: str
    role: str
    disposition: str
    licence: str | None
    redistributable: bool
    rationale: str


def git(*args: str) -> list[str]:
    root = layout.repository_root()
    result = subprocess.run(["git", *args], cwd=str(root),
                            capture_output=True, text=True)
    if result.returncode:
        raise Refused("git " + " ".join(args) + " failed: "
                      + result.stderr.strip()[-300:])
    return result.stdout.splitlines()


def adjudications() -> dict[str, dict]:
    """Owner rulings, indexed by the single path each names."""
    import yaml

    root = layout.repository_root()
    path = root / ADJUDICATIONS
    if not path.is_file():
        raise Refused(
            ADJUDICATIONS + " is missing. It records the rulings that "
            "override a derived disposition, and without it an override "
            "would be invisible rather than absent.")
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    found: dict[str, dict] = {}
    for entry in raw.get("adjudications") or []:
        for required in ("path", "disposition", "why", "decided",
                         "decided_by"):
            if not entry.get(required):
                raise Refused(
                    "an adjudication in %s declares no %r: %r"
                    % (ADJUDICATIONS, required, entry))
        if entry["path"] in found:
            raise Refused("two adjudications name " + entry["path"])
        if entry["disposition"] not in (CONTENT, SOFTWARE, CITED,
                                        VENDORED):
            raise Refused("unknown disposition %r in %s"
                          % (entry["disposition"], ADJUDICATIONS))
        found[entry["path"]] = entry
    return found


def rules(relative: str, owner) -> list[tuple[str, str, str]]:
    """Every rule that matches, so overlap is visible rather than resolved."""
    matched: list[tuple[str, str, str]] = []

    if owner is not None:
        role = owner.role
        if role in CITED_ROLES:
            matched.append((
                CITED, role,
                "third-party reference material, consulted and cited; this "
                "repository grants no rights over it and must not "
                "redistribute it"))
        elif role in VENDORED_ROLES:
            matched.append((
                VENDORED, role,
                {"vendored-ontology":
                     "a pinned extract of a third-party ontology",
                 "vendored-asset":
                     "a pinned third-party file the site serves",
                 "source-evidence":
                     "third-party text harvested at a pinned commit as "
                     "inventory evidence"}[role]
                + ", redistributed under the upstream licence and "
                  "requiring attribution"))
        elif role in SOFTWARE_ROLES:
            matched.append((SOFTWARE, role, "repository tooling"))
        elif role in LICENCE_ROLES:
            matched.append((CONTENT, role,
                            "the repository's own licence text"))
        elif role in CONTENT_ROLES:
            matched.append((CONTENT, role, "project-authored content"))
        else:
            raise Refused(
                "%s belongs to component %s whose role %r has no licensing "
                "rule. Add one deliberately rather than letting the file "
                "fall through to a suffix guess."
                % (relative, owner.id, role))
        return matched

    # No component claims it. Fall back to suffix, and say so, because a
    # file nothing declares is a file nobody decided about.
    name = Path(relative).name
    suffix = Path(relative).suffix.lower()
    if "/" not in relative and (name in CONFIG_NAMES
                                or name.startswith("requirements")):
        matched.append((SOFTWARE, "(undeclared)",
                        "repository configuration at the root"))
    elif relative.startswith((".github/", "tools/", "tests/", "config/")):
        matched.append((SOFTWARE, "(undeclared)",
                        "under a tooling directory"))
    elif suffix in SOFTWARE_SUFFIXES:
        matched.append((SOFTWARE, "(undeclared)", "software by suffix"))
    elif suffix in CONTENT_SUFFIXES:
        matched.append((CONTENT, "(undeclared)", "content by suffix"))
    return matched


def classify() -> list[Disposition]:
    ruled = adjudications()
    out: list[Disposition] = []
    problems: list[str] = []

    for relative in git("ls-files"):
        if relative in ruled:
            entry = ruled[relative]
            out.append(Disposition(
                relative, "(adjudicated)", entry["disposition"],
                entry.get("licence",
                          licence_of(entry["disposition"], relative)),
                entry["disposition"] != CITED,
                "owner ruling %s: %s" % (entry["decided"], entry["why"])))
            continue

        owner = layout.owning_component(relative)
        matched = rules(relative, owner)
        if len(matched) != 1:
            problems.append(
                "%s matches %d disposition rules%s"
                % (relative, len(matched),
                   "" if matched else " -- nothing declares it and no "
                                     "suffix rule reaches it"))
            continue
        disposition, role, why = matched[0]
        out.append(Disposition(relative, role, disposition,
                               licence_of(disposition, relative),
                               disposition != CITED, why))

    unused = sorted(set(ruled) - {row.path for row in out})
    if unused:
        problems.append(
            "adjudications naming no tracked file: %s -- an exception "
            "granted for nothing reads as coverage" % unused)

    if problems:
        raise Refused("licensing could not be determined:\n  "
                      + "\n  ".join(problems))
    return out


def attribution_findings(rows) -> list:
    """Redistribution on condition, with the condition checked.

    Every vendored licence here permits redistribution provided
    attribution travels with the work. `vendor/NOTICE.md` and
    `vendor/site/NOTICE.md` are generated, which makes each right on the
    day it is written and says nothing about the day a source is added and
    the notice is not regenerated. So the pins are read here and each
    declared attribution is required to appear in the notice its own
    generator writes: an upstream extract's in vendor/NOTICE.md, a site
    asset's in vendor/site/NOTICE.md. One finding per notice, upstream
    first.
    """
    out = []
    vendored = [r for r in rows if r.disposition == VENDORED]
    if not vendored:
        return out

    root = layout.repository_root()
    sources = redistributed_sources()
    by_notice: dict[str, list] = {}
    for row in vendored:
        entry, notice = sources[row.path]
        by_notice.setdefault(notice, []).append((row, entry))

    for notice_name in sorted(by_notice, key=lambda n: (n != NOTICE, n)):
        pairs = by_notice[notice_name]
        notice = root / notice_name
        if not notice.is_file():
            out.append(
                "%d vendored file(s) are tracked and %s does not exist. "
                "Their licences permit redistribution on condition of "
                "attribution, and this repository is redistributing "
                "without it." % (len(pairs), notice_name))
            continue
        flat = " ".join(notice.read_text(encoding="utf-8").split())
        missing = []
        for row, entry in pairs:
            attribution = " ".join(entry["licence"]["attribution"].split())
            if attribution not in flat:
                missing.append("%s: %s" % (row.path, attribution))
        if missing:
            out.append(
                "%d vendored file(s) are redistributed without the "
                "attribution their licence requires appearing in %s:"
                % (len(missing), notice_name)
                + chr(10) + "    " + (chr(10) + "    ").join(missing))
    return out


def findings(rows: list[Disposition]) -> list[str]:
    """What is wrong, as opposed to what is unusual."""
    out = attribution_findings(rows)
    not_publishable = [r for r in rows if not r.redistributable]
    if not_publishable:
        out.append(
            "%d tracked file(s) may not be redistributed but are committed, "
            "and are therefore published wherever this repository is:\n    %s"
            % (len(not_publishable),
               "\n    ".join(r.path for r in not_publishable)))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", default=None, metavar="DISPOSITION")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if anything unpublishable is tracked")
    args = ap.parse_args(argv)

    rows = classify()

    if args.list:
        for row in rows:
            if row.disposition == args.list:
                print("%-18s %s" % (row.licence or "(no rights granted)",
                                    row.path))
        return 0

    print("  %d tracked file(s), each with exactly one disposition"
          % len(rows))
    counts: dict[tuple, int] = {}
    for row in rows:
        key = (row.disposition, row.licence or "(no rights granted)")
        counts[key] = counts.get(key, 0) + 1
    for (disposition, licence), count in sorted(counts.items()):
        print("    %-26s %-14s %4d" % (disposition, licence, count))

    problems = findings(rows)
    if problems:
        print()
        for problem in problems:
            print("  FINDING: %s" % problem)
        if any(not row.redistributable for row in rows):
            print()
            print("  Citing a source and shipping it are different acts. A "
                  "README saying the repository does not redistribute "
                  "these is not a licence; the repository's contents are.")
    if args.check:
        return 1 if problems else 0
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
